// ============================================================================
//  hotctl.h — UDP 热参数通道: webui 经 127.0.0.1:47700 下发白名单参数
//    (t/y/x/fov/padthr/spdx/spdy/adsspdx/adsspdy/k/aim/padcalib/cap_*), 固件侧
//    强制钳制后写入共享原子, 即时生效不重启; 结构常量仍为编译期 — 白名单里的是人手
//    输入 (延迟与速度刻度), 律本身没有可调常数。padcalib=1 = 请求手柄标定 (io/calib_run.h, 一次消费即清)。
//  解析与应用是纯函数 hotctl_apply(key,val): 收发循环只做拆包, 单测可直接调用
//    它验证接受/拒绝与钳制, 不必起 socket。
// ============================================================================

#pragma once

// 应用一对 key=value。返回值: true = 已应用 (日志已打印), false = 未接受
//   (白名单外 / 值非法), 两种情形都在控制台留一行说明。
bool hotctl_apply(const char* key, const char* val);

// 收发循环: 白名单外的整对忽略, 应用即打印 (经日志确认生效)。
void hotctl_thread();
